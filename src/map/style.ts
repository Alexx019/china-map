// Capas que necesitan sprites (flechas de sentido único, escudos): no aportan nada aquí
const DROP = new Set(['roads_oneway', 'roads_shields']);

function basemap(isDark: boolean): LayerSpecification[] {
  return layers('protomaps', isDark ? dark : light, { lang: 'en' })
    .filter((l) => !DROP.has(l.id))
    .map((l) => {
      if (!('layout' in l) || !l.layout) return l as LayerSpecification;
      // Sin sprite: quitar iconos (el punto de las localidades) y dejar solo el texto
      const layout = Object.fromEntries(Object.entries(l.layout).filter(([k]) => !k.startsWith('icon-')));
      return { ...l, layout } as LayerSpecification;
    });
}

export const PLACES_SOURCE = 'places';

export function buildStyle(isDark: boolean, places: FeatureCollection): StyleSpecification {
  const origin = window.location.origin;
  return {
    version: 8,
    glyphs: `${origin}/map/fonts/{fontstack}/{range}.pbf`,
    sources: {
      protomaps: {
        type: 'vector',
        url: `pmtiles://${origin}/map/trip.pmtiles`,
        attribution: '<a href="https://www.openstreetmap.org/copyright">© OpenStreetMap</a> · <a href="https://protomaps.com">Protomaps</a>',
      },
      [PLACES_SOURCE]: {
        type: 'geojson',
        data: places,
        cluster: true,
        clusterRadius: 46,
        clusterMaxZoom: 13,
      },
    },
    layers: [
      ...basemap(isDark),
      // Capa invisible: hace que se carguen los sitios. Los marcadores se dibujan en HTML (markers.ts)
      { id: 'places-anchor', type: 'circle', source: PLACES_SOURCE, paint: { 'circle-radius': 1, 'circle-opacity': 0 } },
    ],
  };
}
